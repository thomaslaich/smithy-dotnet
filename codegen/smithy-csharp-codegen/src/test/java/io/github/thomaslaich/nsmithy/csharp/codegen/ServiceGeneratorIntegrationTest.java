package io.github.thomaslaich.nsmithy.csharp.codegen;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.github.thomaslaich.nsmithy.csharp.codegen.integrations.CSharpIntegration;
import io.github.thomaslaich.nsmithy.csharp.codegen.integrations.CSharpServiceGenerator;
import io.github.thomaslaich.nsmithy.csharp.codegen.writer.CSharpWriter;
import java.nio.file.Path;
import java.util.List;
import java.util.Optional;
import org.junit.jupiter.api.Test;
import software.amazon.smithy.build.MockManifest;
import software.amazon.smithy.codegen.core.CodegenException;
import software.amazon.smithy.codegen.core.directed.CodegenDirector;
import software.amazon.smithy.model.Model;
import software.amazon.smithy.model.node.Node;
import software.amazon.smithy.model.node.ObjectNode;
import software.amazon.smithy.model.shapes.ServiceShape;

class ServiceGeneratorIntegrationTest {

  private static final String MODEL =
      """
      $version: "2"
      namespace example.messaging

      service Messaging {
          version: "2024-01-01"
          operations: [Send]
      }

      operation Send {
          input := { text: String }
      }
      """;

  @Test
  void anIntegrationReplacesTheServiceSurface() {
    MockManifest manifest = generate(List.of(new MessagingIntegration()));

    assertTrue(manifest.hasFile(Path.of("Example/Messaging/Messaging.Messaging.g.cs")));
    assertFalse(manifest.hasFile(Path.of("Example/Messaging/Messaging.Client.g.cs")));
    assertFalse(manifest.hasFile(Path.of("Example/Messaging/Messaging.Server.g.cs")));
    // Shapes are still generated by the host generator.
    assertTrue(manifest.hasFile(Path.of("Example/Messaging/SendInput.g.cs")));
  }

  @Test
  void servicesWithoutAServiceGeneratorKeepTheGeneratedSurface() {
    MockManifest manifest = generate(List.of(new PlainIntegration()));

    assertTrue(manifest.hasFile(Path.of("Example/Messaging/Messaging.Client.g.cs")));
  }

  @Test
  void twoServiceGeneratorsForOneServiceAreRejected() {
    CodegenException exception =
        assertThrows(
            CodegenException.class,
            () -> generate(List.of(new MessagingIntegration(), new MessagingIntegration())));

    assertTrue(exception.getMessage().contains("example.messaging#Messaging"));
  }

  private static MockManifest generate(List<CSharpIntegration> integrations) {
    Model model = Model.assembler().addUnparsedModel("messaging.smithy", MODEL).assemble().unwrap();
    CSharpSettings settings =
        CSharpSettings.fromNode(
            ObjectNode.builder()
                .withMember("service", Node.from("example.messaging#Messaging"))
                .withMember("baseNamespace", Node.from(""))
                .build());
    MockManifest manifest = new MockManifest();

    CodegenDirector<CSharpWriter, CSharpIntegration, GenerationContext, CSharpSettings> runner =
        new CodegenDirector<>();
    runner.settings(settings);
    runner.directedCodegen(new DirectedCSharpCodegen());
    runner.fileManifest(manifest);
    runner.service(settings.service());
    runner.model(model);
    runner.integrationClass(CSharpIntegration.class);
    runner.integrationFinder(() -> integrations);
    runner.performDefaultCodegenTransforms();
    runner.createDedicatedInputsAndOutputs();
    runner.run();
    return manifest;
  }

  private static final class MessagingIntegration implements CSharpIntegration {
    @Override
    public String name() {
      return "messaging-" + System.identityHashCode(this);
    }

    @Override
    public Optional<CSharpServiceGenerator> serviceGenerator(
        GenerationContext context, ServiceShape service) {
      return Optional.of(
          (ctx, shape) ->
              ctx.writerDelegator()
                  .useFileWriter(
                      "Example/Messaging/Messaging.Messaging.g.cs",
                      "Example.Messaging",
                      writer -> writer.write("public sealed class MessagingProducer { }")));
    }
  }

  private static final class PlainIntegration implements CSharpIntegration {}
}
