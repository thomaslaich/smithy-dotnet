/*
 * Collects generated F# code into Types.g.fs, Schemas.g.fs, and Client.g.fs, and orders them.
 *
 * F# compiles a project's files in order and a file's declarations in order, so a type can only
 * refer to one declared before it. Each file holds one section per Smithy namespace, declared
 * `namespace rec` so the types (or schemas) of one namespace can refer to each other freely, and
 * the sections come in dependency order. Schemas.g.fs comes after Types.g.fs, since every schema
 * refers to the types it reads and writes, and Client.g.fs comes last.
 */
package io.github.thomaslaich.nsmithy.fsharp.codegen;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import software.amazon.smithy.build.FileManifest;
import software.amazon.smithy.codegen.core.CodegenException;
import software.amazon.smithy.model.shapes.Shape;
import software.amazon.smithy.model.shapes.ShapeId;
import software.amazon.smithy.utils.SmithyInternalApi;

@SmithyInternalApi
public final class FSharpFiles {

  /** The generated files, in the order a project compiles them. */
  public static final List<String> FILES = List.of("Types.g.fs", "Schemas.g.fs", "Client.g.fs");

  private static final String HEADER =
      "// <auto-generated />\n// Generated by smithy-fsharp-codegen. DO NOT EDIT.\n";

  /** Sections by Smithy namespace. */
  private final Map<String, Section> sections = new TreeMap<>();

  /** The section a shape's type is declared in. */
  public FSharpWriter types(Shape shape) {
    return section(shape).types;
  }

  /**
   * The section a string or int enum's schema is declared in. Enum schemas come before the other
   * schemas of their namespace: they are referenced directly, not lazily, so they must be
   * initialized first.
   */
  public FSharpWriter enumSchemas(Shape shape) {
    return section(shape).enumSchemas;
  }

  /** The section the schema of a structure, union, list, or map is declared in. */
  public FSharpWriter schemas(Shape shape) {
    return section(shape).schemas;
  }

  /** The section a service's client is declared in. */
  public FSharpWriter client(Shape service) {
    return section(service).client;
  }

  private Section section(Shape shape) {
    Section section =
        sections.computeIfAbsent(shape.getId().getNamespace(), namespace -> new Section());
    section.shapes.add(shape);
    return section;
  }

  /** Writes the files. A project that generates nothing gets no files. */
  void write(FileManifest manifest, FSharpSettings settings) {
    List<String> order = order();
    StringBuilder types = new StringBuilder();
    StringBuilder schemaFile = new StringBuilder();
    StringBuilder clientFile = new StringBuilder();
    for (String namespace : order) {
      Section section = sections.get(namespace);
      String fsharpNamespace = settings.fsharpNamespace(namespace);
      String typeCode = section.types.toString().strip();
      if (!typeCode.isEmpty()) {
        types.append("\nnamespace rec ").append(fsharpNamespace).append("\n\n");
        types.append(typeCode).append('\n');
      }
      String schemaCode =
          (section.enumSchemas.toString().strip() + "\n\n" + section.schemas.toString().strip())
              .strip();
      if (!schemaCode.isEmpty()) {
        schemaFile
            .append("\nnamespace rec ")
            .append(fsharpNamespace)
            .append('.')
            .append(FSharpSymbolProvider.SCHEMAS_NAMESPACE)
            .append("\n\n");
        schemaFile.append(schemaCode.replaceAll("\n{3,}", "\n\n")).append('\n');
      }
      String clientCode = section.client.toString().strip();
      if (!clientCode.isEmpty()) {
        clientFile.append("\nnamespace ").append(fsharpNamespace).append("\n\n");
        clientFile.append(clientCode).append('\n');
      }
    }
    if (!types.isEmpty()) {
      manifest.writeFile(FILES.get(0), HEADER + types);
    }
    if (!schemaFile.isEmpty()) {
      manifest.writeFile(FILES.get(1), HEADER + schemaFile);
    }
    if (!clientFile.isEmpty()) {
      manifest.writeFile(FILES.get(2), HEADER + clientFile);
    }
  }

  /**
   * The namespaces in dependency order: a namespace comes after every namespace whose shapes its
   * shapes refer to. Namespaces that do not depend on each other keep their alphabetical order.
   */
  private List<String> order() {
    Map<String, Set<String>> dependencies = new TreeMap<>();
    for (Map.Entry<String, Section> entry : sections.entrySet()) {
      Set<String> needs = new TreeSet<>();
      for (Shape shape : entry.getValue().shapes) {
        for (ShapeId referenced : references(shape)) {
          String target = referenced.getNamespace();
          if (!target.equals(entry.getKey()) && sections.containsKey(target)) {
            needs.add(target);
          }
        }
      }
      dependencies.put(entry.getKey(), needs);
    }

    List<String> order = new ArrayList<>();
    Set<String> remaining = new LinkedHashSet<>(dependencies.keySet());
    while (!remaining.isEmpty()) {
      String next =
          remaining.stream()
              .filter(namespace -> order.containsAll(dependencies.get(namespace)))
              .findFirst()
              .orElseThrow(() -> cycle(remaining));
      order.add(next);
      remaining.remove(next);
    }
    return order;
  }

  /** The shapes a shape's type or schema refers to. */
  private static List<ShapeId> references(Shape shape) {
    List<ShapeId> references = new ArrayList<>();
    shape.members().forEach(member -> references.add(member.getTarget()));
    shape
        .asOperationShape()
        .ifPresent(
            operation -> {
              references.add(operation.getInputShape());
              references.add(operation.getOutputShape());
              references.addAll(operation.getErrors());
            });
    return references;
  }

  private static CodegenException cycle(Set<String> namespaces) {
    return new CodegenException(
        "The shapes of the Smithy namespaces "
            + String.join(", ", namespaces)
            + " refer to each other. F# compiles one namespace after another, so a namespace can"
            + " only refer to the namespaces before it. Move the shapes that refer to each other"
            + " into one namespace, for example with the renameShapes build transform.");
  }

  private static final class Section {
    private final Set<Shape> shapes = new LinkedHashSet<>();
    private final FSharpWriter types = new FSharpWriter();
    private final FSharpWriter enumSchemas = new FSharpWriter();
    private final FSharpWriter schemas = new FSharpWriter();
    private final FSharpWriter client = new FSharpWriter();
  }
}
